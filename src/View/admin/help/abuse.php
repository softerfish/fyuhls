<div class="p-1">
    <p class="guide-purpose mb-4">The <strong>Abuse Reports</strong> view is a filtered moderation lens on the unified ticket system. Use it for malware, phishing, scam uploads, and other policy-violation work that usually needs file or account action more than a conversational reply.</p>

    <h6 class="fw-bold text-dark border-bottom pb-2 mb-3">When To Use This View</h6>
    <ul class="extra-small text-muted mb-4">
        <li class="mb-2"><strong>Use it when:</strong> You want to focus only on abuse-type tickets and moderation work.</li>
        <li><strong>Use Tickets instead when:</strong> You need the full mixed queue or want to compare abuse items against support/contact backlog at the same time.</li>
    </ul>

    <h6 class="fw-bold text-dark border-bottom pb-2 mb-3">Review Pattern</h6>
    <ol class="guide-steps mb-4">
        <li><strong>Confirm the claim type:</strong> Separate malware, phishing, copyright confusion, and ordinary broken-link complaints before you act.</li>
        <li><strong>Inspect the affected record safely:</strong> Move into Files or an investigation page if the complaint looks like part of a broader uploader or content pattern.</li>
        <li><strong>Leave a factual note:</strong> Document why the file was removed, kept, or escalated so the next moderator is not guessing later.</li>
    </ol>

    <div class="alert alert-danger border-0 shadow-sm small mb-3">
        <strong>Safety guard:</strong> Do not investigate suspicious files on your own workstation. Confirm through safe moderation and server-side review workflows instead.
    </div>

