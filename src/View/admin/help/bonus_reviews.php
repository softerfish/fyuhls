    <h6 class="fw-bold text-dark mb-3">Bonus Reviews</h6>
    <p class="small text-muted">This view is the review-focused slice of the Monetization tab. It is for Configuration staff who need to evaluate pending bonus-offer awards without leaving the broader monetization workflow.</p>

    <div class="mb-4">
        <div class="fw-bold small text-primary mb-1">What You Can See Here</div>
        <ul class="extra-small text-muted ps-3">
            <li><strong>Offer queue:</strong> Shows the active bonus offers that currently need review attention or operator follow-up.</li>
            <li><strong>Submission progress:</strong> Helps staff understand what the user was trying to qualify for before approving or rejecting an award.</li>
            <li><strong>Decision controls:</strong> Lets Configuration staff approve, reject, or leave items pending depending on the evidence on the screen.</li>
        </ul>
    </div>

    <div class="mb-4">
        <div class="fw-bold small text-primary mb-1">What Changing Something Does</div>
        <ul class="extra-small text-muted ps-3">
            <li><strong>Approve:</strong> Turns the reviewed bonus into a real credited award, so it can affect the user's visible rewards history and balance trail.</li>
            <li><strong>Reject:</strong> Prevents that submission from becoming a credit and keeps the review trail attached to the offer.</li>
            <li><strong>Leave pending:</strong> Keeps the submission in the queue when more evidence or staff review is still needed.</li>
        </ul>
    </div>

    <div class="mb-4">
        <div class="fw-bold small text-primary mb-1">Good Review Habits</div>
        <ul class="extra-small text-muted ps-3">
            <li><strong>Check the offer rule first:</strong> Make sure the submission actually matches the campaign you think it belongs to.</li>
            <li><strong>Keep notes consistent:</strong> If a rejection or approval could be questioned later, explain it in the bonus workflow while the evidence is fresh.</li>
        </ul>
    </div>

