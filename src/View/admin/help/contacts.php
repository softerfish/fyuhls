<div class="p-1">
    <p class="guide-purpose mb-4">The <strong>Contacts</strong> view is now a filtered lens on the unified ticket system. Use it when you want to focus only on public contact submissions without the rest of the queue in view.</p>

    <h6 class="fw-bold text-dark border-bottom pb-2 mb-3">When To Use This View</h6>
    <ul class="extra-small text-muted mb-4">
        <li class="mb-2"><strong>Use it when:</strong> You are working ordinary support questions, account issues, billing questions, or partner inquiries from the public contact form.</li>
        <li><strong>Use Tickets instead when:</strong> You need the full mixed queue with support, abuse, and DMCA together.</li>
    </ul>

    <h6 class="fw-bold text-dark border-bottom pb-2 mb-3">Best Workflow</h6>
    <ol class="guide-steps mb-4">
        <li><strong>Read the source first:</strong> Confirm whether the item is really a public contact request and not something that should be moved into a broader support or moderation workflow.</li>
        <li><strong>Reply or note clearly:</strong> Keep customer-facing replies short and use internal notes for staff-only handoff context.</li>
        <li><strong>Close after the real handoff:</strong> If you told the sender to continue through tickets or billing follow-up, close only when that routing is actually complete.</li>
    </ol>

