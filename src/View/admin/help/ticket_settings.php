<div class="help-section">
    <h6 class="fw-bold text-dark mb-3">Ticket Settings</h6>
    <p class="small text-muted">This Config Hub tab controls how the unified request inbox behaves. Use it when you want to change how support tickets, contact submissions, abuse reports, or DMCA notices are accepted, rate-limited, or emailed.</p>

    <div class="mb-4">
        <div class="fw-bold small text-primary mb-1">Main Feature Areas</div>
        <ul class="extra-small text-muted ps-3">
            <li><strong>Inbox address and notifications:</strong> Decide where ticket email goes and when staff should be alerted.</li>
            <li><strong>Rate limits:</strong> Control how often visitors can open support, contact, abuse, or DMCA requests from one IP.</li>
            <li><strong>Reminder behavior:</strong> Controls the “waiting on user” follow-up cadence so old tickets do not silently stall forever.</li>
        </ul>
    </div>

    <div class="mb-4">
        <div class="fw-bold small text-primary mb-1">What Changing It Does</div>
        <ul class="extra-small text-muted ps-3">
            <li><strong>Notification changes:</strong> Alter who sees new request activity first, which can speed up response time or reduce inbox noise.</li>
            <li><strong>Rate-limit changes:</strong> Make abuse harder or easier depending on how aggressive you set them. Higher limits are more convenient; lower limits are safer.</li>
            <li><strong>Reminder timing changes:</strong> Affect how quickly inactive tickets get nudged, which changes both queue pressure and user experience.</li>
        </ul>
    </div>

    <div class="alert alert-light border-0 small py-2 mb-0">
        <strong>Use this tab for:</strong> inbox-wide rules. <strong>Use the Tickets page instead when:</strong> you are replying to one request, adding notes, changing a single ticket status, or processing a DMCA removal.
    </div>
</div>
