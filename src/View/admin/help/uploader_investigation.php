<div class="help-section">
    <h6 class="fw-bold text-dark mb-3">Uploader Investigation</h6>
    <p class="small text-muted">Use this page when one uploader needs a deeper review than the normal Users page provides. It pulls together account, file, and rewards-adjacent context in one place so staff can investigate without jumping across multiple screens.</p>

    <div class="mb-4">
        <div class="fw-bold small text-primary mb-1">Main Areas On The Page</div>
        <ul class="extra-small text-muted ps-3">
            <li><strong>Account snapshot:</strong> Shows who the uploader is, what package they are on, and the status context that matters during moderation or fraud review.</li>
            <li><strong>File activity:</strong> Lists the files tied to that uploader so staff can spot patterns like repeated uploads, unusual naming, or storage issues.</li>
            <li><strong>Rewards and moderation context:</strong> Surfaces the information that helps explain whether the uploader’s recent activity looks normal, risky, or worth escalating.</li>
        </ul>
    </div>

    <div class="mb-4">
        <div class="fw-bold small text-primary mb-1">What Actions Mean</div>
        <ul class="extra-small text-muted ps-3">
            <li><strong>Open file details:</strong> Drills into one file when the issue is not the uploader broadly, but one specific asset or link.</li>
            <li><strong>Jump to Users:</strong> Use the normal user edit page when you are changing package, status, password recovery, or other account controls.</li>
            <li><strong>Jump to Rewards Fraud:</strong> Use the dedicated rewards review queue when the decision is really about held or suspicious reward activity.</li>
        </ul>
    </div>

    <div class="alert alert-light border-0 small py-2 mb-0">
        <strong>Tip:</strong> This page is best for investigation and context gathering. Make account or payout decisions on the dedicated admin pages so the action trail stays where operators expect it.
    </div>
</div>
